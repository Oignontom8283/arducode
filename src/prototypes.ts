/** Analyse pure (sans vscode) du .ino.cpp généré par arduino-cli et des arguments gcc. */
import * as fs from 'fs';
import * as path from 'path';

const KNOWN = new Set(('void bool boolean char byte word short int long float double signed unsigned const volatile static inline extern struct class enum size_t ssize_t wchar_t ' +
  'String uint8_t uint16_t uint32_t uint64_t int8_t int16_t int32_t int64_t uintptr_t intptr_t Print Stream HardwareSerial __FlashStringHelper').split(' '));

/** Prototypes insérés par Arduino : « #line N "f" » puis une déclaration sur une ligne. */
export function extractPrototypes(inoCpp: string): string[] {
  const lines = inoCpp.split(/\r?\n/), out: string[] = [];
  for (let i = 1; i < lines.length; i++) {
    if (/^#line \d+ "/.test(lines[i - 1]) && /^[\w:<>,*&\s~[\]]+\(.*\)\s*;$/.test(lines[i]) && (i + 1 >= lines.length || /^#line \d+ "/.test(lines[i + 1]))) { out.push(lines[i].trim()); }
  }
  return out;
}

/** En-tête forcé pour l'IntelliSense : Arduino.h + prototypes dont les types sont déclarables avant le croquis. */
export function prototypeHeader(inoCpp: string): string {
  const body = inoCpp.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
  const local = new Map<string, string>();
  for (const m of body.matchAll(/^\s*(struct|class|union)\s+(\w+)\s*(?:final\s*)?(?::[^;{]*)?\{/gm)) { local.set(m[2], m[1]); }
  const macros = new Set([...body.matchAll(/^\s*#\s*define\s+(\w+)/gm)].map(m => m[1]));
  // Types impossibles à pré-déclarer : typedef, using, enum.
  const opaque = new Set([...body.matchAll(/\b(?:using\s+(\w+)\s*=|enum\s+(?:class\s+|struct\s+)?(\w+)|typedef\b[^;{]*?\b(\w+)\s*;|\}\s*(\w+)\s*;)/g)].map(m => m[1] ?? m[2] ?? m[3] ?? m[4]));
  const decls = new Set<string>(), protos: string[] = [];
  let needIncludes = false;
  for (const p of extractPrototypes(inoCpp)) {
    if (p.includes('=') || /\btemplate\b/.test(p)) { continue; }
    const open = p.indexOf('(');
    const head = p.slice(0, open).replace(/\w+\s*$/, '');
    // Dans chaque paramètre, le dernier identifiant est le nom, sauf s'il est seul.
    const params = p.slice(open + 1, p.lastIndexOf(')')).split(',').map(a => {
      const types = (a.match(/\w+/g) ?? []).filter(x => !['const', 'volatile', 'struct'].includes(x));
      return types.length > 1 ? a.replace(/\b\w+\s*(\[[^\]]*\]\s*)*$/, '') : a;
    });
    const words = [head, ...params].join(' ').match(/[A-Za-z_]\w*/g) ?? [];
    if (words.some(w => opaque.has(w) || macros.has(w))) { continue; }
    for (const w of words) {
      if (KNOWN.has(w)) { continue; }
      const kind = local.get(w);
      if (kind) { decls.add(`${kind} ${w};`); } else { needIncludes = true; }
    }
    protos.push(p);
  }
  const includes = needIncludes ? [...body.matchAll(/^\s*#\s*include\s*(<[^>]+>|"[^"]+")/gm)].map(m => `#include ${m[1]}`) : [];
  return ['// Generated by Arducode for IntelliSense, do not edit.', '#pragma once', '#include <Arduino.h>',
    ...new Set(includes), ...decls, ...protos, ''].join('\n');
}

export interface GccConfig { compiler: string; includes: string[]; defines: string[]; args: string[]; standard?: string; forced: string[] }

/** Découpe un fichier de réponse gcc (@fichier, utilisé par les cœurs ESP32/RP2040). */
export function splitResponse(s: string): string[] {
  return [...s.matchAll(/(?:[^\s"'\\]|\\[\s\S]|"(?:\\[\s\S]|[^"\\])*"|'[^']*')+/g)].map(m =>
    m[0].replace(/"((?:\\[\s\S]|[^"\\])*)"|'([^']*)'|\\([\s\S])/g, (_a, d, q, e) => d !== undefined ? d.replace(/\\(["\\])/g, '$1') : q !== undefined ? q : e));
}

export function parseGcc(argv: string[], cwd: string): GccConfig {
  const c: GccConfig = { compiler: argv[0], includes: [], defines: [], args: [], forced: [] };
  const abs = (p: string) => path.resolve(cwd, p);
  const expand = (args: string[], depth: number): string[] => args.flatMap(a => {
    if (a[0] !== '@' || depth > 5) { return [a]; }
    try { return expand(splitResponse(fs.readFileSync(abs(a.slice(1)), 'utf8')), depth + 1); } catch { return []; }
  });
  const args = expand(argv.slice(1), 0);
  let prefix = '';
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    const take = (flag: string) => a === flag ? args[++i] ?? '' : a.slice(flag.length);
    if (a.startsWith('-iprefix')) { prefix = take('-iprefix'); }
    else if (a.startsWith('-iwithprefixbefore')) { c.includes.push(abs(prefix + take('-iwithprefixbefore'))); }
    else if (a.startsWith('-iwithprefix')) { c.includes.push(abs(prefix + take('-iwithprefix'))); }
    else if (a.startsWith('-isystem')) { c.includes.push(abs(take('-isystem'))); }
    else if (a.startsWith('-include')) { c.forced.push(abs(take('-include'))); }
    else if (a.startsWith('-I')) { c.includes.push(abs(take('-I'))); }
    else if (a.startsWith('-D')) { c.defines.push(take('-D')); }
    else if (a.startsWith('-std=')) { c.standard = a.slice(5); }
    else if (/^-m/.test(a) || /^-f(no-)?(exceptions|rtti|permissive|short-enums)$/.test(a)) { c.args.push(a); }
  }
  c.includes = [...new Set(c.includes)];
  return c;
}
